import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { argv, exit, stdout } from 'node:process';

/**
 * Writes the public surface of the library to a file, so that a change to what
 * this package exports shows up in a diff rather than in somebody else's build.
 *
 * Nothing here runs at import time. A script that regenerates its own output as
 * a side effect of being imported rewrites the file the test is about to
 * compare against, and the check then passes no matter what.
 */
const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const srcDir = join(root, 'src');
const outputPath = join(root, 'docs', 'surface.md');

const EXPORT_PATTERN =
  /^export\s+(?:declare\s+)?(?:async\s+)?(function|const|class|interface|type|enum)\s+([A-Za-z0-9_]+)/;

async function walk(directory) {
  const found = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) {
      found.push(...(await walk(path)));
      continue;
    }
    if (entry.name.endsWith('.ts')) {
      found.push(path);
    }
  }
  return found;
}

export function exportsIn(text) {
  const names = [];
  for (const line of text.split('\n')) {
    const match = EXPORT_PATTERN.exec(line);
    if (match !== null) {
      names.push({ kind: match[1], name: match[2] });
    }
  }
  // Sorted by code point rather than by locale. A generated file that is
  // checked in has to come out byte identical on every machine, and
  // localeCompare orders Fourth before first on one runner and after it on
  // another, which turns the surface check into a coin toss.
  return names.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
}

export async function collectSurface() {
  const files = (await walk(srcDir)).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  const modules = [];
  for (const path of files) {
    const key = relative(root, path).split(sep).join('/');
    if (key === 'src/index.ts' || key.startsWith('src/bin/')) {
      continue;
    }
    const names = exportsIn(await readFile(path, 'utf8'));
    if (names.length > 0) {
      modules.push({ module: key, names });
    }
  }
  return modules;
}

export function renderSurface(modules) {
  const total = modules.reduce((sum, entry) => sum + entry.names.length, 0);
  const lines = [
    '# Public surface',
    '',
    'Generated by `npm run docs`. Do not edit by hand.',
    '',
    `${modules.length} modules export ${total} names.`,
    '',
  ];
  for (const entry of modules) {
    lines.push(`## ${entry.module}`, '');
    for (const name of entry.names) {
      lines.push(`- \`${name.kind} ${name.name}\``);
    }
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

export async function writeSurface() {
  const text = renderSurface(await collectSurface());
  await writeFile(outputPath, text, 'utf8');
  return text;
}

export async function checkSurface() {
  const wanted = renderSurface(await collectSurface());
  let current = '';
  try {
    current = await readFile(outputPath, 'utf8');
  } catch {
    return { ok: false, reason: 'docs/surface.md has not been generated' };
  }
  return current === wanted
    ? { ok: true, reason: 'the surface file matches the source' }
    : { ok: false, reason: 'docs/surface.md is out of date, run npm run docs' };
}

if (argv[1]?.endsWith('surface.mjs') === true) {
  const mode = argv[2] ?? 'write';
  if (mode === 'check') {
    const result = await checkSurface();
    stdout.write(`${result.reason}\n`);
    exit(result.ok ? 0 : 1);
  } else {
    await writeSurface();
    stdout.write(`wrote ${relative(root, outputPath)}\n`);
    exit(0);
  }
}
